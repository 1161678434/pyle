# 场景 2：尖峰测试（SpikeLoadShape）— 测系统"瞬间爆发"
# ============================================================
"""
模拟秒杀、抢票：用户数在 10 秒内从 10 跳到 100，再回落到 10

观察什么：
  - 尖峰期间失败率有没有暴涨？
  - 尖峰结束后系统能不能恢复？（有些系统冲击过后持续慢）
  - 数据库连接池/线程池有没有被打爆？

关键指标：恢复时间
  尖峰退去后，响应时间多久回到正常水平？
  如果 5 秒内恢复 → 弹性好
  如果一直降不下来 → 资源泄漏或排队积压
"""

