# 场景 3：稳定性负载（SoakLoadShape）— 测"扛多久"
# ============================================================
"""
保持固定用户数，跑 1 小时/4 小时/24 小时

专门抓这些问题：
  - 内存泄漏（内存一直涨不释放）
  - 数据库连接泄漏（连接池耗尽）
  - 日志文件把磁盘写满
  - GC 停顿越来越长

和阶梯测试的区别：
  阶梯测"扛多大"         ← 找上限
  稳定性测"扛多久"        ← 找慢性病

稳定性测试是最容易被跳过的，但它抓的问题往往是生产事故的根源
"""

