# 场景 1：阶梯加压（StepLoadShape）— 找系统上限
# ============================================================
"""
像爬楼梯：5→10→20→40 用户，每档停 30 秒

目的是找到两个点：
  ① 拐点：RPS 不再线性增长的那个用户数
  ② 崩溃点：响应时间 P95 飙升 + 失败率出现的那个用户数

这两个点之间的区域 = 系统的"安全运行区间"

面试官问"你们系统能扛多少并发"：
  回答拐点，不是崩溃点。拐点是"正常运行的最大值"
  崩溃点是"开始出问题的值"——没人想跑到崩溃点
"""

# TODO 1.1：跑一次 StepLoadShape，观察从哪一档开始
#           RPS 不再翻倍增长？这个用户数就是拐点
# 答：拐点大概在 __30__ 用户，因为 ____服务资源到达了上限_____________
# 拐点 = RPS 不再随用户数线性增长的那个点。
# 从实际跑的结果看：5→10→20→40 全程未崩，说明本地 Flask dev server 的上限 > 40 用户。
# 要找到真正的拐点需要继续加档（80、160、320），直到 RPS 曲线变平。
# "服务资源到了上限"应该是 CPU 打满 / 线程池耗尽 / 数据库连接池耗尽，不是笼统的"资源"。_


