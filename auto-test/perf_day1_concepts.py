# ============================================================
# 概念 1：响应时间（Response Time）— 单位 ms
# ============================================================
"""
上面的 Avg=4、Min=3、Max=14、Med=4 是什么意思？

  Avg（平均值）：所有请求的响应时间加起来 ÷ 请求数
     上面 36 个请求平均 4ms —— 看起来很健康
     但！Avg 会骗人：10 个请求 9 个 3ms + 1 个 1000ms = Avg 102.7ms
     实际上大部分请求很慢，被一个快请求拉低

  Med / 50%（中位数 / P50）：一半请求在多少 ms 内完成
     上面 P50 = 4ms → 50% 的请求 4ms 内完成
     比平均值更诚实，不受极端值影响

  P95 / P99：95% / 99% 的请求在多少 ms 内完成
     上面 P95 = 7ms → 95% 请求 7ms 内完成
     如果 P95 是 500ms，说明虽然有极端慢请求但 95% 还算快

  面试官问"这个接口性能怎么样"：
    正确回答：P50 4ms，P95 7ms，P99 15ms，无失败
    错误回答：平均 4ms ← 信息太少
"""

