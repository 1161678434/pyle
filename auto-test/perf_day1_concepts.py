# ============================================================
# 概念 2：TPS / QPS（每秒事务数 / 每秒请求数）
# ============================================================
"""
上面的 req/s = 3.92 是什么意思？

  3.92 req/s = 这个接口每秒能处理约 4 个请求（5 个用户并发时）

  TPS（Transactions Per Second）：每秒处理多少笔"业务"
  QPS / RPS（Requests Per Second）：每秒处理多少个 HTTP 请求
      严格说 RPS 是底层指标，TPS 是业务指标
      但面试和实际工作中经常混用，知道是一个意思就行

  影响因素：并发用户数 ↑ → TPS ↑，直到服务器瓶颈 → TPS 不再增长甚至下降

  上面用的用户数：
    -u 5   = 5 个并发用户
    -r 2   = 每秒增加 2 个用户
    -t 10s = 跑 10 秒
"""

# TODO 1.2：上面 5 个用户跑出 3.92 req/s，你觉得 10 个用户会是多少？
#           更高的 req/s 一定更好吗？
# 答：1因为 wait_time = between(1,2)，
# 每个用户每秒只有约 0.5～1 次请求，大部分时间在"等"。
# 5 个用户填不满服务器。10 个用户 = 更多人在等 = 更多请求塞进等待间隙 = TPS 升高。
# 但 TPS 不会无限涨——服务器 CPU 打满时 TPS 就到顶了，再加用户 TPS 反而下降（排队越来越长）。
# 高了不一定好，要看服务器资源利用率，盲目堆用户反而浪费___________________


# ============================================================
# 概念 3：并发（Concurrency）vs 并行（Parallelism）
# ============================================================
"""
  并发 ≠ 并行

  并发（Concurrency）：
    一个 CPU 在多个任务间快速切换               ← 单核机器也能并发
    比如 locust 的 5 个虚拟用户并不是同时发出请求，而是交替发

  并行（Parallelism）：
    多个 CPU 同时执行多个任务                   ← 必须多核

  性能测试测的是"并发"——模拟 N 个用户同时在线，交替发请求
  比如 100 个并发用户 ≠ 100 个请求同时打在服务器上
      是 100 个用户在发出请求、等待响应、再发下一个
      每个用户的行为由 wait_time 控制
"""

# TODO 1.3：locustfile.py 里 wait_time = between(1, 2) 是什么意思？
#           如果改成 between(0, 0)（不等），压测结果会有什么变化？
# 答：___wait_time = between(1, 2) 等待在1~2秒之间进来，
# 改成between(0, 0)，between(0,0) = 用户不间断轰炸服务器，TPS 会飙升到服务器极限。
# 但你永远不该这样做——真实用户不会 0 间隔连续点击，
# 这样的压测数据没有意义。_______________________________


# ============================================================
# 概念 4：吞吐量（Throughput）— 单位时间处理的数据量
# ============================================================
"""
  吞吐量 = TPS × 每次请求的数据大小
  通常用 KB/s 或 MB/s 衡量

  上面每个响应约 50-70 bytes，36 个请求 ≈ 2.5KB / 10s
  吞吐量 = 0.25 KB/s —— 因为本地服务器、响应极小

  吞吐量 vs TPS 的区别：
    TPS：每秒处理多少"个"请求（计数）
    吞吐量：每秒处理多少"数据"（容量）
    比如下载大文件，TPS 很低但吞吐量很高
"""


# ============================================================
# 概念 5：失败率 — 性能测试的底线
# ============================================================
"""
上面的 # fails = 0(0.00%)

  失败率 = 失败的请求数 ÷ 总请求数 × 100%
  一般要求失败率 < 0.1%，核心接口要求 0%

  为什么性能测试会有失败？
    - 服务器过载返回 502/503
    - 连接超时
    - 数据库连接池耗尽

  面试常见问题："什么时候该停止加压？"
  答案：失败率开始上涨 + 响应时间 P95 急剧恶化 → 这就是系统瓶颈点
"""

# TODO 1.4：如果把并发用户逐步加到 50、100、200，你预计哪个指标先崩溃？
#           为什么？
# 答：最快请求速度，因为请求剧增，会导致请求处理越来越慢
# 50 用户  → P95 开始上涨（偶尔排队）
# 100 用户 → P95 翻倍、Avg 明显变慢
# 200 用户 → 失败率 > 0%（服务器开始丢 502/503）
# 先看 P95，再等失败率，两者同时恶化就是瓶颈点
