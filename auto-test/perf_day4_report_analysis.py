# ============================================================
"""
性能测试发现问题后，不是甩一句"太慢了"——要能指向具体层：

  第一层：应用代码层（最常见）
    慢 SQL、N+1 查询、没加索引、循环里调 HTTP
    → 查 APM（如 SkyWalking、New Relic）

  第二层：连接池/线程池
    数据库连接池满了在排队、HTTP 连接池耗尽
    → 看配置：pool_size、max_connections

  第三层：基础设施
    CPU 打满、内存不够、带宽跑满
    → top / htop / 云监控

  第四层：下游依赖
    调的第三方 API 慢了、Redis 响应变长
    → 看分布式追踪（trace）
"""

