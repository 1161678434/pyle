"""
GitHub Actions 是 GitHub 自带的 CI/CD 工具，免费额度够个人/小团队用。

核心概念：
  workflow（流水线）  = 一个 YAML 文件，定义"什么时候、做什么"
  job（任务）         = 流水线里的一个大步骤（如"跑测试"）
  step（步骤）        = 任务里的一小步（如"pip install"、"pytest"）
  trigger（触发器）   = 什么时候启动流水线（push / PR / 定时）

下面的 YAML 文件翻译成你手动做的事：
"""

# ============================================================
# TODO 2.1：看这份流水线配置，回答后面的问题
# ============================================================
"""
name: 接口自动化测试                    ← 流水线名字

on:
  push:                                 ← 触发器：每次 git push 自动跑
    branches: [main]
  pull_request:                         ← 触发器：每次提 PR 自动跑
    branches: [main]
  schedule:
    - cron: '0 8 * * *'                ← 触发器：每天早上 8 点定时跑

jobs:
  test:
    runs-on: ubuntu-latest              ← 在 GitHub 的 Ubuntu 机器上跑

    steps:
      - name: 检出代码
        uses: actions/checkout@v4       ← git clone

      - name: 安装 Python
        uses: actions/setup-python@v5
        with:
          python-version: '3.12'

      - name: 安装依赖
        run: |
          pip install -r requirements.txt
          pip install pytest allure-pytest

      - name: 启动测试服务器
        run: |
          python auto-test/api_test_server.py &
          sleep 2

      - name: 运行测试
        run: |
          cd auto-test
          pytest api_day5_real_api.py -v --alluredir=reports --junitxml=reports/junit.xml

      - name: 上传 allure 报告
        if: always()                    ← 测试失败也要上传报告
        uses: actions/upload-artifact@v4
        with:
          name: test-report
          path: auto-test/reports/

      - name: 停止测试服务器
        if: always()
        run: kill $(lsof -t -i:5000)
"""

# 2.1：如果凌晨 3 点有人提交了代码，流水线会触发吗？为什么？
# 答：___提交了就会跑，会跑第一个push的触发器_______________________________

# 2.2：`if: always()` 是什么意思？如果不加这行，测试失败了报告还能上传吗？
# 答：__清理环境和上报状态__，能上传__________________
# 不加 if: always() → pytest 失败了 → 后续步骤全部跳过 → 报告上传不执行 → 没有任何输出来排查问题。
# 加了之后不管成败都上传报告，失败时就能看到是哪个用例挂了。____________

# 2.3：这份流水线里哪一步是你"本地不用做，但 CI 必须做"的？
# 答：___停止测试服务器_______________________________


# ============================================================
# Part 3：流水线设计原则
# ============================================================
"""
  ① 每个 push 都跑 — 问题发现越早修复成本越低
  ② 失败就阻止合并 — PR 测试不通过不能合入 main
  ③ 测试要快 — 单元测试 < 5 分钟，接口测试 < 15 分钟
     太慢没人愿意等，开发者会选择跳过
  ④ 报告要留存 — 失败了能回溯"哪次提交引入的问题"
  ⑤ 不要在生产环境跑 — CI 用独立的测试环境
"""

