# ============================================================
# Part 1：CI/CD 三个词一句话
# ============================================================
"""
CI（持续集成）：代码一提交，自动跑测试。过了才算"集成成功"
               你现在手动跑 pytest = CI 要自动做的事

CD（持续交付）：测试过了后自动打包，点一下按钮就上线
               不是全自动，需要人点一下"确认发布"

CD（持续部署）：测试过了全自动上线，人不插手
                git push → 测试 → 打包 → 部署 → 一条龙全自动
"""

